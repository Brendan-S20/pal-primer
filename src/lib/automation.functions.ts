import { createServerFn } from "@tanstack/react-start";
import { z } from "zod";
import { requireSupabaseAuth } from "@/integrations/supabase/auth-middleware";
import { netDaysSchema, graceDaysSchema } from "@/lib/billing-settings";

async function resolveOrgId(supabase: any, userId: string): Promise<string> {
  const { data, error } = await supabase
    .from("user_roles")
    .select("organization_id")
    .eq("user_id", userId)
    .maybeSingle();
  if (error) throw new Error(error.message);
  if (!data) throw new Error("No organization for user");
  return data.organization_id as string;
}

export const getAutomationSettings = createServerFn({ method: "GET" })
  .middleware([requireSupabaseAuth])
  .handler(async ({ context }) => {
    const { supabase, userId } = context;
    const orgId = await resolveOrgId(supabase, userId);
    const { data, error } = await supabase
      .from("organizations")
      .select(
        "auto_generate_visits, auto_generate_days_ahead, auto_invoice_enabled, invoice_net_days, invoice_grace_days, overdue_reminders_enabled, overdue_reminder_days, dunning_retry_days, dunning_pause_after_failures, seasonal_deepclean_enabled, seasonal_deepclean_months, notify_sms_overdue_invoice, notify_sms_payment_failed, notify_sms_visit_reminder, notify_sms_on_my_way, notify_sms_visit_completed",
      )
      .eq("id", orgId)
      .single();
    if (error) throw new Error(error.message);
    // invoice_net_days isn't in the generated types yet.
    return data as any as Record<string, any>;
  });

// Every field is optional so a caller can send just the settings it edits and
// this one fn patches only those keys (I3: one server fn owns these org
// columns). The Automation page sends its full payload; the dedicated
// Invoicing page (B9) sends only the client-billing trio. Net/grace reuse the
// shared schemas so their bounds + human-readable messages (I11) match the UI.
const updateSchema = z.object({
  autoGenerateVisits: z.boolean().optional(),
  autoGenerateDaysAhead: z.number().int().min(1).max(60).optional(),
  autoInvoiceEnabled: z.boolean().optional(),
  invoiceNetDays: netDaysSchema.optional(),
  invoiceGraceDays: graceDaysSchema.optional(),
  overdueRemindersEnabled: z.boolean().optional(),
  overdueReminderDays: z.number().int().min(1).max(90).optional(),
  dunningRetryDays: z.array(z.number().int().min(1).max(60)).min(1).max(6).optional(),
  dunningPauseAfterFailures: z.number().int().min(1).max(10).optional(),
  seasonalDeepcleanEnabled: z.boolean().optional(),
  seasonalDeepcleanMonths: z.array(z.number().int().min(1).max(12)).max(12).optional(),
  notifySmsOverdueInvoice: z.boolean().optional(),
  notifySmsPaymentFailed: z.boolean().optional(),
  notifySmsVisitReminder: z.boolean().optional(),
  notifySmsOnMyWay: z.boolean().optional(),
  notifySmsVisitCompleted: z.boolean().optional(),
});

export const updateAutomationSettings = createServerFn({ method: "POST" })
  .middleware([requireSupabaseAuth])
  .inputValidator((d) => updateSchema.parse(d))
  .handler(async ({ data, context }) => {
    const { supabase, userId } = context;
    const orgId = await resolveOrgId(supabase, userId);
    // Patch only the keys the caller actually sent (partial update), so the
    // Invoicing page can save the client-billing trio without clobbering the
    // rest of the automation config, and vice versa.
    const patch: Record<string, unknown> = {};
    if (data.autoGenerateVisits !== undefined) patch.auto_generate_visits = data.autoGenerateVisits;
    if (data.autoGenerateDaysAhead !== undefined) patch.auto_generate_days_ahead = data.autoGenerateDaysAhead;
    if (data.autoInvoiceEnabled !== undefined) patch.auto_invoice_enabled = data.autoInvoiceEnabled;
    if (data.overdueRemindersEnabled !== undefined) patch.overdue_reminders_enabled = data.overdueRemindersEnabled;
    if (data.overdueReminderDays !== undefined) patch.overdue_reminder_days = data.overdueReminderDays;
    if (data.dunningRetryDays !== undefined) patch.dunning_retry_days = data.dunningRetryDays;
    if (data.dunningPauseAfterFailures !== undefined) patch.dunning_pause_after_failures = data.dunningPauseAfterFailures;
    if (data.seasonalDeepcleanEnabled !== undefined) patch.seasonal_deepclean_enabled = data.seasonalDeepcleanEnabled;
    if (data.seasonalDeepcleanMonths !== undefined) patch.seasonal_deepclean_months = data.seasonalDeepcleanMonths;
    if (data.notifySmsOverdueInvoice !== undefined) patch.notify_sms_overdue_invoice = data.notifySmsOverdueInvoice;
    if (data.notifySmsPaymentFailed !== undefined) patch.notify_sms_payment_failed = data.notifySmsPaymentFailed;
    if (data.notifySmsVisitReminder !== undefined) patch.notify_sms_visit_reminder = data.notifySmsVisitReminder;
    if (data.notifySmsOnMyWay !== undefined) patch.notify_sms_on_my_way = data.notifySmsOnMyWay;
    if (data.notifySmsVisitCompleted !== undefined) patch.notify_sms_visit_completed = data.notifySmsVisitCompleted;
    if (data.invoiceNetDays !== undefined) patch.invoice_net_days = data.invoiceNetDays;
    if (data.invoiceGraceDays !== undefined) patch.invoice_grace_days = data.invoiceGraceDays;
    if (Object.keys(patch).length === 0) return { ok: true };
    const { error } = await supabase.from("organizations").update(patch as any).eq("id", orgId);
    if (error) throw new Error(error.message);
    return { ok: true };
  });
