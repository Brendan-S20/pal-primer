// Pure mapping from the automation-settings input (camelCase, validated by the
// zod schema in automation.functions.ts) to the organizations-table patch
// (snake_case columns). Extracted so the partial-update / anti-clobber
// behavior is unit-testable without a server context (QA round 3 phase 5,
// finding F3): the Invoicing page and the Automation page each send only their
// own keys, and this must patch ONLY the keys present — an omitted key must
// never appear in the patch (which would clobber the other page's config).

/** camelCase input key -> organizations column. The single source of the
 *  field list, shared by the update server fn and its tests. */
export const AUTOMATION_FIELD_MAP = {
  autoGenerateVisits: "auto_generate_visits",
  autoGenerateDaysAhead: "auto_generate_days_ahead",
  autoInvoiceEnabled: "auto_invoice_enabled",
  invoiceNetDays: "invoice_net_days",
  invoiceGraceDays: "invoice_grace_days",
  overdueRemindersEnabled: "overdue_reminders_enabled",
  overdueReminderDays: "overdue_reminder_days",
  dunningRetryDays: "dunning_retry_days",
  dunningPauseAfterFailures: "dunning_pause_after_failures",
  seasonalDeepcleanEnabled: "seasonal_deepclean_enabled",
  seasonalDeepcleanMonths: "seasonal_deepclean_months",
  notifySmsOverdueInvoice: "notify_sms_overdue_invoice",
  notifySmsPaymentFailed: "notify_sms_payment_failed",
  notifySmsVisitReminder: "notify_sms_visit_reminder",
  notifySmsOnMyWay: "notify_sms_on_my_way",
  notifySmsVisitCompleted: "notify_sms_visit_completed",
} as const;

export type AutomationInput = Partial<Record<keyof typeof AUTOMATION_FIELD_MAP, unknown>>;

/** Build the DB patch from ONLY the keys the caller actually sent. An omitted
 *  key is absent from the result (not set to null), so a partial payload never
 *  overwrites a field the caller didn't touch. */
export function buildAutomationPatch(data: AutomationInput): Record<string, unknown> {
  const patch: Record<string, unknown> = {};
  for (const [inputKey, column] of Object.entries(AUTOMATION_FIELD_MAP)) {
    const v = data[inputKey as keyof typeof AUTOMATION_FIELD_MAP];
    if (v !== undefined) patch[column] = v;
  }
  return patch;
}
