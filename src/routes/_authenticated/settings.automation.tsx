import { createFileRoute, Link } from "@tanstack/react-router";
import { useServerFn } from "@tanstack/react-start";
import { useMutation, useSuspenseQuery, queryOptions } from "@tanstack/react-query";
import { useEffect, useState } from "react";
import {
  getAutomationSettings,
  updateAutomationSettings,
} from "@/lib/automation.functions";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Button } from "@/components/ui/button";
import { toast } from "sonner";
import { pageTitle } from "@/lib/page-title";
import { useClientTexting } from "@/hooks/useClientTexting";
import { ComingSoonBadge } from "@/components/ComingSoonBadge";
import { useServiceLines } from "@/components/CommercialOnly";

const key = ["automation"] as const;

export const Route = createFileRoute("/_authenticated/settings/automation")({
  head: () => ({ meta: [{ title: pageTitle("Automation", "Settings") }] }),
  component: AutomationPage,
});

function AutomationPage() {
  const load = useServerFn(getAutomationSettings);
  const save = useServerFn(updateAutomationSettings);
  const opts = queryOptions({ queryKey: key, queryFn: () => load() });
  const { data, refetch } = useSuspenseQuery(opts);
  // Until this business has its own texting number, the text-only switches
  // below are a state: drawn off, locked, and badged Coming soon. Their
  // STORED values are untouched: the form state still holds what was loaded
  // and saves it back unchanged, so a business that had a text turned on
  // still has it on the day texting arrives.
  const texting = useClientTexting();
  // The seasonal deep clean is a pet-waste idea (a spring yard after a
  // winter's accumulation). Hidden from a business that does not run pet
  // waste -- unless it is ON, because then it is adding a charge to real
  // invoices and the owner has to be able to find the switch. Hiding only:
  // the form still saves the loaded value back unchanged.
  const { petWaste } = useServiceLines();
  const showSeasonal = petWaste || !!data.seasonal_deepclean_enabled;

  const [autoGen, setAutoGen] = useState(data.auto_generate_visits);
  const [days, setDays] = useState(data.auto_generate_days_ahead);
  const [remOn, setRemOn] = useState(data.overdue_reminders_enabled);
  const [remDays, setRemDays] = useState(data.overdue_reminder_days);
  const [ladder, setLadder] = useState<string>((data.dunning_retry_days ?? [1, 3, 7]).join(", "));
  const [pauseAfter, setPauseAfter] = useState<number>(data.dunning_pause_after_failures ?? 3);
  const [seasonalOn, setSeasonalOn] = useState<boolean>(data.seasonal_deepclean_enabled ?? false);
  const [seasonalMonths, setSeasonalMonths] = useState<number[]>(data.seasonal_deepclean_months ?? [3, 10]);
  const [nOverdue, setNOverdue] = useState<boolean>(data.notify_sms_overdue_invoice ?? true);
  const [nPayFail, setNPayFail] = useState<boolean>(data.notify_sms_payment_failed ?? true);
  const [nVisitRem, setNVisitRem] = useState<boolean>(data.notify_sms_visit_reminder ?? true);
  const [nOnWay, setNOnWay] = useState<boolean>(data.notify_sms_on_my_way ?? true);
  const [nDone, setNDone] = useState<boolean>(data.notify_sms_visit_completed ?? true);
  const [onWayNav, setOnWayNav] = useState<boolean>(data.on_my_way_on_navigate ?? false);
  const [liveTracking, setLiveTracking] = useState<boolean>(data.live_tracking_enabled ?? false);

  useEffect(() => {
    setAutoGen(data.auto_generate_visits);
    setDays(data.auto_generate_days_ahead);
    setRemOn(data.overdue_reminders_enabled);
    setRemDays(data.overdue_reminder_days);
    setLadder((data.dunning_retry_days ?? [1, 3, 7]).join(", "));
    setPauseAfter(data.dunning_pause_after_failures ?? 3);
    setSeasonalOn(data.seasonal_deepclean_enabled ?? false);
    setSeasonalMonths(data.seasonal_deepclean_months ?? [3, 10]);
    setNOverdue(data.notify_sms_overdue_invoice ?? true);
    setNPayFail(data.notify_sms_payment_failed ?? true);
    setNVisitRem(data.notify_sms_visit_reminder ?? true);
    setNOnWay(data.notify_sms_on_my_way ?? true);
    setNDone(data.notify_sms_visit_completed ?? true);
    setOnWayNav(data.on_my_way_on_navigate ?? false);
    setLiveTracking(data.live_tracking_enabled ?? false);
  }, [data]);

  const mut = useMutation({
    mutationFn: () => {
      const parsedLadder = ladder
        .split(/[,\s]+/)
        .map((s) => Number(s))
        .filter((n) => Number.isFinite(n) && n > 0 && n <= 60);
      if (parsedLadder.length === 0) throw new Error("Enter at least one retry day (e.g. 1, 3, 7)");
      return save({
        data: {
          autoGenerateVisits: autoGen,
          autoGenerateDaysAhead: days,
          overdueRemindersEnabled: remOn,
          overdueReminderDays: remDays,
          dunningRetryDays: parsedLadder.slice(0, 6),
          dunningPauseAfterFailures: pauseAfter,
          seasonalDeepcleanEnabled: seasonalOn,
          seasonalDeepcleanMonths: seasonalMonths,
          notifySmsOverdueInvoice: nOverdue,
          notifySmsPaymentFailed: nPayFail,
          notifySmsVisitReminder: nVisitRem,
          notifySmsOnMyWay: nOnWay,
          notifySmsVisitCompleted: nDone,
          onMyWayOnNavigate: onWayNav,
          liveTrackingEnabled: liveTracking,
        },
      });
    },
    onSuccess: () => {
      toast.success("Automation settings saved");
      refetch();
    },
    onError: (e: Error) => toast.error(e.message),
  });

  const MONTHS = ["Jan","Feb","Mar","Apr","May","Jun","Jul","Aug","Sep","Oct","Nov","Dec"];
  const toggleMonth = (m: number) =>
    setSeasonalMonths((prev) => prev.includes(m) ? prev.filter((x) => x !== m) : [...prev, m].sort((a, b) => a - b));

  return (
    <div className="space-y-6">
      <div>
        <h2 className="text-lg font-semibold">Automation</h2>
        <p className="text-sm text-muted-foreground">
          A nightly worker runs these tasks against your organization.
        </p>
      </div>

      <Card>
        <CardHeader><CardTitle>Recurring visit generation</CardTitle></CardHeader>
        <CardContent className="space-y-3">
          <label className="flex items-center gap-2 text-sm">
            <input type="checkbox" checked={autoGen} onChange={(e) => setAutoGen(e.target.checked)} />
            Auto-generate visits from active subscriptions nightly
          </label>
          <div className="max-w-xs">
            <Label htmlFor="days">Days ahead to generate</Label>
            <Input
              id="days"
              type="number"
              min={1}
              max={365}
              value={days}
              onChange={(e) => setDays(Number(e.target.value))}
              disabled={!autoGen}
            />
          </div>
        </CardContent>
      </Card>

      <Card>
        <CardHeader><CardTitle>Client invoicing</CardTitle></CardHeader>
        <CardContent className="space-y-3">
          <p className="text-sm text-muted-foreground">
            Automatic invoicing, net payment terms, and the invoice grace period now live in their
            own place: <Link to="/settings/invoicing" className="text-primary underline">Settings &rsaquo; Invoicing</Link>.
          </p>
          <Button asChild variant="outline" size="sm">
            <Link to="/settings/invoicing">Open invoicing settings</Link>
          </Button>
        </CardContent>
      </Card>

      <Card>
        <CardHeader><CardTitle>Overdue reminders</CardTitle></CardHeader>
        <CardContent className="space-y-3">
          <label className="flex items-center gap-2 text-sm touch:min-h-11">
            <input type="checkbox" checked={remOn} onChange={(e) => setRemOn(e.target.checked)} />
            Send a reminder when an open invoice is past due
          </label>
          <div className="max-w-xs">
            <Label htmlFor="remdays">Days past the due date before reminding</Label>
            <Input
              id="remdays"
              type="number"
              min={1}
              max={90}
              value={remDays}
              onChange={(e) => setRemDays(Number(e.target.value))}
              disabled={!remOn}
            />
          </div>
          <p className="text-xs text-muted-foreground">
            {texting
              ? "By email, and by text to clients who have agreed to texts. "
              : "By email, to clients who have not opted out. Texting your clients is coming soon; the text part of this reminder starts then. "}
            Reminders re-send at most every {remDays} day(s).
          </p>
        </CardContent>
      </Card>

      <Card>
        <CardHeader><CardTitle>Failed-payment dunning ladder</CardTitle></CardHeader>
        <CardContent className="space-y-3">
          <div className="max-w-md">
            <Label htmlFor="ladder">Retry days after first failure</Label>
            <Input
              id="ladder"
              value={ladder}
              onChange={(e) => setLadder(e.target.value)}
              placeholder="1, 3, 7"
            />
            <p className="mt-1 text-xs text-muted-foreground">
              Comma-separated days. Default 1, 3, 7 means retry the card 1 day, 3 days, and 7 days after the first failure.
            </p>
          </div>
          <div className="max-w-xs">
            <Label htmlFor="pauseAfter">Pause service after N total failures</Label>
            <Input
              id="pauseAfter"
              type="number"
              min={1}
              max={10}
              value={pauseAfter}
              onChange={(e) => setPauseAfter(Number(e.target.value))}
            />
            <p className="mt-1 text-xs text-muted-foreground">
              Client keeps a paused subscription until they update payment; visits stop being generated.
            </p>
          </div>
        </CardContent>
      </Card>

      {showSeasonal && (
      <Card>
        <CardHeader><CardTitle>Seasonal deep-clean campaign</CardTitle></CardHeader>
        <CardContent className="space-y-3">
          <label className="flex items-center gap-2 text-sm">
            <input type="checkbox" checked={seasonalOn} onChange={(e) => setSeasonalOn(e.target.checked)} />
            Auto-offer deep cleans to active clients each season
          </label>
          <div>
            <Label>Campaign months</Label>
            <div className="mt-1 flex flex-wrap gap-1.5">
              {MONTHS.map((label, i) => {
                const m = i + 1;
                const on = seasonalMonths.includes(m);
                return (
                  <button
                    key={m}
                    type="button"
                    onClick={() => toggleMonth(m)}
                    disabled={!seasonalOn}
                    // 26px tall, and never measured until 2026-09-28: the
                    // sweep had no fixture for this page and drew its error
                    // boundary instead. Same floor /settings/deep-clean uses.
                    className={`rounded border px-2 py-1 text-xs touch:min-h-11 touch:min-w-11 shrink-0 ${on ? "bg-primary text-primary-foreground border-primary" : "bg-background text-muted-foreground"} disabled:opacity-50`}
                  >
                    {label}
                  </button>
                );
              })}
            </div>
            <p className="mt-1 text-xs text-muted-foreground">
              On the 1st of each selected month, every active service gets a deep-clean visit
              added, billed at your deep-clean charge on top of the regular visit.
            </p>
          </div>
        </CardContent>
      </Card>
      )}

      <Card>
        <CardHeader><CardTitle>On my way</CardTitle></CardHeader>
        <CardContent className="space-y-2">
          <label className="flex min-h-11 items-center justify-between gap-3 rounded border px-3 py-2 text-sm">
            <span className="min-w-0">
              Tell the client when a tech taps Navigate
              <span className="mt-0.5 block text-xs text-muted-foreground">
                Once per visit, for today&apos;s stops, with the tech&apos;s first name and the
                arrival window.{" "}
                {texting
                  ? "By text when the client can be texted, otherwise by email."
                  : "By email. Texting your clients is coming soon."}
              </span>
            </span>
            <input
              type="checkbox"
              className="shrink-0"
              checked={onWayNav}
              onChange={(e) => setOnWayNav(e.target.checked)}
            />
          </label>
          <label className="flex min-h-11 items-center justify-between gap-3 rounded border px-3 py-2 text-sm">
            <span className="min-w-0">
              Include a live map of the tech on the way
              <span className="mt-0.5 block text-xs text-muted-foreground">
                The on-my-way text and email get a link. From the moment that message goes until
                the tech starts the visit (two hours at most), the client sees the tech&apos;s
                approximate position, rounded to about 100 m, and only while the tech has the app
                open. Nothing is shared before the message or after the visit starts, and no
                trail is kept: only the latest position, deleted when the visit starts. Techs see
                a banner whenever their location is being shared, and can stop it.
              </span>
            </span>
            <input
              type="checkbox"
              className="shrink-0"
              checked={liveTracking}
              onChange={(e) => setLiveTracking(e.target.checked)}
            />
          </label>
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <CardTitle className="flex flex-wrap items-center gap-2">
            Text notifications
            {!texting && <ComingSoonBadge />}
          </CardTitle>
        </CardHeader>
        <CardContent className="space-y-2">
          <p className="text-xs text-muted-foreground">
            {texting ? (
              "Turn individual automated texts on or off. A client is texted only once they have agreed to texts and have not replied STOP."
            ) : (
              <>
                Texting your clients is coming soon. Until then, these messages go by email: the
                overdue and declined-card reminders, the day-before reminder, the on-my-way notice
                and the visit-completed note each have their own switch in{" "}
                <Link to="/settings/emails" className="text-primary underline">
                  Settings &rsaquo; Emails
                </Link>
                .
              </>
            )}
          </p>
          {[
            { label: "Overdue invoice reminder", val: nOverdue, set: setNOverdue },
            { label: "Card payment failed alert", val: nPayFail, set: setNPayFail },
            { label: "Day-before visit reminder", val: nVisitRem, set: setNVisitRem },
            { label: '"On my way" text', val: nOnWay, set: setNOnWay },
            { label: "Visit completed confirmation", val: nDone, set: setNDone },
          ].map((row) => (
            <label
              key={row.label}
              className={`flex min-h-11 items-center justify-between gap-2 rounded border px-3 py-2 text-sm ${texting ? "" : "text-muted-foreground"}`}
            >
              <span className="min-w-0">{row.label}</span>
              <input
                type="checkbox"
                className="shrink-0"
                checked={texting ? row.val : false}
                disabled={!texting}
                onChange={(e) => row.set(e.target.checked)}
              />
            </label>
          ))}
        </CardContent>
      </Card>


      <Button onClick={() => mut.mutate()} disabled={mut.isPending}>
        {mut.isPending ? "Saving…" : "Save automation settings"}
      </Button>
    </div>
  );
}
