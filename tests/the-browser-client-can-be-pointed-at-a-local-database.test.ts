import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";

// Until 2026-09-19 the browser could not be pointed anywhere. client.ts
// hardcoded the production URL and anon key with no way to override them, while
// client.server.ts read process.env.SUPABASE_URL — so a local run was split
// down the middle: server functions on the local database, the browser on the
// live one. That is why credentials the E2E seed had just used successfully
// came back `Invalid login credentials`, and why the E2E suite had to proxy
// every browser request in-process (tests/e2e/point-the-browser-at-the-local-
// database.ts, which stays, as the proof this test is about the file and not
// about making that suite pass).
//
// The fix is deliberately narrower than the server's resolveSupabaseUrl():
// the override only exists in `vite dev`. import.meta.env.DEV is statically
// false in a production build, so the whole branch compiles out and NO build
// environment — Lovable's, Capacitor's, anyone's — can repoint the shipped
// app. The literals are what production ships, always.
//
// ── WHY A TEST HOLDS THE SHAPE ──────────────────────────────────────────────
//
// client.ts says of itself "This file is automatically generated" and the
// Lovable agent edits it from a browser, reading the project knowledge rather
// than this repo's tests or CLAUDE.md. If a regeneration drops the env reads,
// nothing fails at runtime: the fallback is production, local dev silently
// starts writing to the live database again, and the E2E proxy keeps that
// suite green. A silent revert to the dangerous state is exactly what a test
// must make loud. (The knowledge for project da34c6c7 carries the same rule;
// per CLAUDE.md, a change to this shape is a change in two places.)

const SRC = readFileSync("src/integrations/supabase/client.ts", "utf8")
  // Comments in the file explain the mechanism by name; match code, not prose.
  .replace(/^\s*\/\/.*$/gm, "");

describe("the browser Supabase client", () => {
  it("reads VITE_SUPABASE_URL in dev, so a local run is not split down the middle", () => {
    expect(SRC).toMatch(/import\.meta\.env\.DEV\s*&&\s*import\.meta\.env\.VITE_SUPABASE_URL/);
  });

  it("reads VITE_SUPABASE_PUBLISHABLE_KEY the same way, because a local stack rejects the production anon key", () => {
    expect(SRC).toMatch(
      /import\.meta\.env\.DEV\s*&&\s*import\.meta\.env\.VITE_SUPABASE_PUBLISHABLE_KEY/,
    );
  });

  it("never reads the env WITHOUT the DEV guard, so no build environment can repoint production", () => {
    // Every read of a VITE_SUPABASE_* variable in this file must sit directly
    // behind `import.meta.env.DEV &&`. An unguarded read is the dangerous
    // variant: a value injected at build time would move where the shipped
    // app sends every user's data, silently.
    const reads = SRC.match(/import\.meta\.env\.VITE_SUPABASE_\w+/g) ?? [];
    const guarded =
      SRC.match(/import\.meta\.env\.DEV\s*&&\s*import\.meta\.env\.VITE_SUPABASE_\w+/g) ?? [];
    expect(reads.length).toBeGreaterThan(0);
    expect(guarded.length).toBe(reads.length);
  });

  it("keeps the production URL as the fallback, so an unset env changes nothing", () => {
    // `||`, not `??`: an empty string in the env must fall through to the
    // literal rather than produce same-origin requests to the app itself —
    // the same lesson tests/the-supabase-url-is-not-a-secret.test.ts records.
    expect(SRC).toMatch(/\|\|\s*\n?\s*"https:\/\/api\.houndstack\.com"/);
  });
});
