// Driving the HoundStack app from inside the simulator.
//
// ── WHY THIS EXISTS ───────────────────────────────────────────────────────
//
// The 2026-08-20 QA pass drove the simulator from the host with AppleScript,
// which needs macOS Accessibility permission. That worked until it didn't:
// mid-pass the grant was revoked, and re-granting does not reach a process that
// was already running — Terminal would have had to be relaunched, killing the
// session doing the testing. Three device checks were left unfinished with no
// way to reach them.
//
// XCUITest runs INSIDE the simulator. It needs no host permission, cannot be
// revoked out from under a run, and does not care what is in the foreground on
// the Mac. That is the whole reason this target exists.
//
// ── WHY A SEPARATE PROJECT, NOT A TARGET IN App.xcodeproj ─────────────────
//
// `ios/App/App.xcodeproj` is Capacitor's. It is regenerated by `npx cap add
// ios` and touched by Capacitor upgrades, so a target added there is a target
// that can be clobbered by a tool that knows nothing about it. This project is
// standalone and drives the app by BUNDLE ID, so it never needs to reference
// the app target at all — which also means it keeps working if the app project
// is regenerated from scratch.
//
// ── TALKING TO A WEBVIEW ──────────────────────────────────────────────────
//
// Almost everything on screen is DOM inside a WKWebView, surfaced to XCUITest
// through WebKit's accessibility bridge. That mapping is not one-to-one with
// HTML: a <button> may come through as .button, a clickable <div> as .other, a
// link as .link, and plain copy as .staticText. So the helpers below search
// ACROSS element types rather than guessing one, and match on label substrings
// rather than exact strings, because the visible text carries punctuation and
// whitespace that the DOM does not promise to preserve.

import XCTest

enum AppDriver {
    /// The app under test. Addressed by bundle id so this bundle has no build
    /// dependency on the app target.
    static let bundleId = "consulting.thenorth.houndstack"

    /// Generous. A cold launch of this app on a simulator has been measured at
    /// ~3.5s to first paint and longer when the machine is busy building; a
    /// tight timeout here produces flakes that look like product bugs.
    static let launchTimeout: TimeInterval = 90
    /// 60s, not 30. This app is not a local fixture: every signed-in surface
    /// waits on api.houndstack.com, and a route like Settings › Billing does
    /// several round trips before it renders "Current plan". At 30s a slow
    /// backend was indistinguishable from a broken page, and full-suite runs
    /// failed roughly every other time on a different surface each run while
    /// the same test passed on its own.
    static let elementTimeout: TimeInterval = 60

    static func app() -> XCUIApplication {
        XCUIApplication(bundleIdentifier: bundleId)
    }

    /// Launch and wait until the WebView has painted something we can act on.
    @discardableResult
    static func launch() -> XCUIApplication {
        let app = self.app()
        app.launch()
        XCTAssertTrue(
            app.wait(for: .runningForeground, timeout: launchTimeout),
            "app did not reach the foreground within \(launchTimeout)s"
        )
        // Reaching the foreground is not the same as having rendered: the
        // splash sits over an empty WebView for a moment. Wait for ANY text.
        let anyText = app.staticTexts.firstMatch
        _ = anyText.waitForExistence(timeout: elementTimeout)
        return app
    }

    /// Take the guided tour down if this launch happened to be a first run.
    /// Silent when there is no tour, so it is safe to call unconditionally.
    ///
    /// CALL THIS AFTER `isSignedIn`, never before and never from `launch`.
    /// The first-run tour is a full-screen modal: while it is up the command
    /// palette cannot be tapped or typed into, and every palette-driven test
    /// dies inside `type` with "Neither element nor any descendant has
    /// keyboard focus" — a message that names nothing to do with a tour.
    /// Running `reset-tour.sh` and then the whole suite failed four unrelated
    /// tests exactly that way on 2026-08-21; they passed on a re-run only
    /// because TourWalk had gone last and dismissed it. Order-dependent tests
    /// are how a suite starts lying.
    ///
    /// It lives outside `launch` because the poll below costs real seconds on
    /// a launch with no tour, and putting that in front of `isSignedIn` made
    /// the sign-in probe time out and SKIP two tests instead.
    ///
    /// POLLS, and that is the whole trick. The tour does not exist at first
    /// paint: it renders only once `useMyRole` has resolved and the auth user
    /// has come back, a second or two later. A single check right after launch
    /// therefore finds nothing, returns happily, and the tour appears
    /// afterwards to block the palette anyway — which is exactly what the
    /// first version of this helper did, and it failed the same four tests it
    /// was written to fix.
    @discardableResult
    static func dismissTourIfPresent(_ app: XCUIApplication, timeout: TimeInterval = 8) -> Bool {
        let deadline = Date().addingTimeInterval(timeout)
        while Date() < deadline {
            if find(app, containing: "Skip tour") != nil {
                let dismissed = tapExactIfPresent(app, "Skip tour")
                usleep(1_000_000)
                return dismissed
            }
            usleep(400_000)
        }
        return false
    }

    // MARK: - Finding things

    /// Every element type a WebView node might surface as, in the order that
    /// tends to match first.
    private static func candidates(_ app: XCUIApplication) -> [XCUIElementQuery] {
        [app.buttons, app.links, app.staticTexts, app.otherElements, app.cells, app.images]
    }

    /// First element whose label contains `text`, across all the types above.
    /// Returns nil rather than failing so callers can assert absence too.
    static func find(_ app: XCUIApplication, containing text: String) -> XCUIElement? {
        let predicate = NSPredicate(format: "label CONTAINS[c] %@", text)
        for query in candidates(app) {
            let match = query.matching(predicate).firstMatch
            if match.exists { return match }
        }
        return nil
    }

    /// Wait for something containing `text`, failing the test with a message
    /// that names what was being waited for.
    @discardableResult
    static func waitFor(
        _ app: XCUIApplication,
        containing text: String,
        timeout: TimeInterval = elementTimeout,
        file: StaticString = #filePath,
        line: UInt = #line
    ) -> XCUIElement {
        let deadline = Date().addingTimeInterval(timeout)
        var polls = 0
        while Date() < deadline {
            if let found = find(app, containing: text), found.exists {
                return found
            }
            // FORCE A FRESH SNAPSHOT every few polls.
            //
            // Element queries are served from a cached accessibility snapshot,
            // and after a run has launched the app several times that cache can
            // go stale against a large WebView — the same staleness that made
            // `allElementsBoundByIndex` report "No matches found for Element at
            // index 64" earlier in this harness. Re-polling a stale snapshot
            // just asks the same wrong question faster, which is how ScrollSweep
            // spent 30s failing to find a palette trigger that a screenshot and
            // a tree dump taken moments earlier both showed present and hittable.
            //
            // `debugDescription` takes a new snapshot as a side effect. Every
            // fourth poll rather than every poll because it is not cheap.
            polls += 1
            if polls % 4 == 0 { _ = app.debugDescription }
            usleep(400_000)
        }
        XCTFail("never found an element containing “\(text)” within \(timeout)s", file: file, line: line)
        return app.staticTexts.firstMatch
    }

    /// True when nothing on screen contains `text`. Used for the store-gate
    /// assertions, where the whole point is that a control is absent.
    static func isAbsent(_ app: XCUIApplication, _ text: String) -> Bool {
        find(app, containing: text) == nil
    }

    /// Has the app settled on a signed-in screen?
    ///
    /// POLLS. A cold launch legitimately shows the sign-in form for a moment:
    /// the app boots at `capacitor://localhost/`, routes/index.tsx sends `/` to
    /// `/auth` unconditionally, and only then does the landing effect move a
    /// signed-in user onward. Reading the screen once catches that transient
    /// and calls a signed-in app signed out — which is how both the first run
    /// of these tests and the first run of the scroll sweep failed.
    static func isSignedIn(_ app: XCUIApplication, timeout: TimeInterval = launchTimeout) -> Bool {
        let deadline = Date().addingTimeInterval(timeout)
        while Date() < deadline {
            // The authenticated chrome, present on every signed-in surface.
            if find(app, containing: "Search or jump") != nil { return true }
            usleep(500_000)
        }
        return false
    }

    // MARK: - Acting

    /// Tap the first element containing `text`.
    ///
    /// `.tap()` on a WebView element can miss when the element's frame is
    /// reported but not hittable (mid-scroll, or behind a sticky header), so
    /// this falls back to a coordinate tap at the element's centre, which is
    /// what the AppleScript harness did and what actually works.
    @discardableResult
    static func tap(
        _ app: XCUIApplication,
        containing text: String,
        timeout: TimeInterval = elementTimeout,
        file: StaticString = #filePath,
        line: UInt = #line
    ) -> Bool {
        let element = waitFor(app, containing: text, timeout: timeout, file: file, line: line)
        guard element.exists else { return false }
        if element.isHittable {
            element.tap()
        } else {
            element.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.5)).tap()
        }
        return true
    }

    /// Tap the element whose label is EXACTLY `label`.
    ///
    /// Substring matching is too loose for short words: "Billing" is a tab, a
    /// palette section, a settings row and a page heading, and `contains` will
    /// happily return whichever the query enumerates first.
    @discardableResult
    static func tapExact(
        _ app: XCUIApplication,
        _ label: String,
        timeout: TimeInterval = elementTimeout,
        file: StaticString = #filePath,
        line: UInt = #line
    ) -> Bool {
        let predicate = NSPredicate(format: "label == %@", label)
        let deadline = Date().addingTimeInterval(timeout)
        while Date() < deadline {
            for query in [app.buttons, app.links, app.otherElements, app.staticTexts] {
                let match = query.matching(predicate).firstMatch
                if match.exists {
                    if match.isHittable { match.tap() }
                    else { match.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.5)).tap() }
                    return true
                }
            }
            usleep(400_000)
        }
        XCTFail("never found an element labelled exactly “\(label)” within \(timeout)s", file: file, line: line)
        return false
    }

    /// Open the command palette, type `query`, and activate the first result
    /// with Return.
    ///
    /// Return rather than a tap because the palette marks its first result
    /// Selected, and because WebView elements report frames in the view's own
    /// coordinate space — a result row comes back 440pt wide on a 402pt screen —
    /// so a coordinate tap does not land where the frame claims. Tapping the
    /// row by label has the same problem in reverse: "Riverside" also matches
    /// the text you just typed INTO the field, so the tap re-focuses the input.
    static func jumpTo(_ app: XCUIApplication, _ query: String) {
        tap(app, containing: "Search or jump")
        type(app, query)
        usleep(1_500_000)
        app.typeText("\n")
    }

    /// Drag horizontally across the window at `atHeight` (0…1 of the screen).
    ///
    /// Window-normalised coordinates are REAL screen coordinates, which is what
    /// makes this usable where element frames are not: a WebView reports its
    /// nodes in the view's own space, so a row can claim to be 440pt wide on a
    /// 402pt screen and a coordinate tap derived from that frame lands nowhere
    /// near the thing.
    static func swipeLeft(_ app: XCUIApplication, atHeight: CGFloat) {
        let start = app.coordinate(withNormalizedOffset: CGVector(dx: 0.92, dy: atHeight))
        let end = app.coordinate(withNormalizedOffset: CGVector(dx: 0.08, dy: atHeight))
        start.press(forDuration: 0.05, thenDragTo: end)
        usleep(700_000)
    }

    /// Open a client's Billing tab.
    ///
    /// Via the "Review" link beside the "No payment method on file" warning on
    /// the Summary tab, NOT via the tab strip. The strip scrolls horizontally
    /// and "Billing" starts off-screen: it is in the accessibility tree the
    /// whole time, so a tap "succeeds" and hits nothing, and swiping to reveal
    /// it overshoots onto "Reviews & referrals" and selects that instead.
    ///
    /// Matched EXACTLY. "Review" as a substring also matches the "Reviews &
    /// referrals" tab, and there is a second exact "Review" further down for a
    /// pricing warning — the payment one comes first in document order.
    ///
    /// Returns false when the warning is not on screen, which is a property of
    /// the demo data rather than of the app; callers skip rather than fail.
    static func openClientBillingTab(_ app: XCUIApplication) -> Bool {
        guard find(app, containing: "No payment method on file") != nil else { return false }
        guard tapExactIfPresent(app, "Review") else { return false }
        return waitForExists(app, containing: "Payment methods", timeout: elementTimeout)
    }

    /// Like `waitFor`, but reports instead of failing.
    static func waitForExists(
        _ app: XCUIApplication,
        containing text: String,
        timeout: TimeInterval
    ) -> Bool {
        let deadline = Date().addingTimeInterval(timeout)
        while Date() < deadline {
            if find(app, containing: text) != nil { return true }
            usleep(400_000)
        }
        return false
    }

    /// Non-failing `tapInSection`, for a sweep that should carry on to the
    /// next surface rather than stop at the first one it cannot reach.
    @discardableResult
    /// The silent sibling of `tapInSection`, for callers that retry: it never
    /// records a failure, so a surface reached on the third attempt does not
    /// leave two failures in the report for the two that missed.
    static func tapInSectionIfPresent(
        _ app: XCUIApplication,
        section: String,
        item: String,
        timeout: TimeInterval = elementTimeout
    ) -> Bool {
        let sectionPredicate = NSPredicate(format: "label == %@", section)
        let itemPredicate = NSPredicate(format: "label == %@", item)
        let deadline = Date().addingTimeInterval(timeout)
        while Date() < deadline {
            let group = app.otherElements.matching(sectionPredicate).firstMatch
            if group.exists {
                let row = group.otherElements.matching(itemPredicate).firstMatch
                if row.exists {
                    if row.isHittable { row.tap() }
                    else { row.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.5)).tap() }
                    return true
                }
            }
            usleep(400_000)
        }
        return false
    }

    /// Non-failing variants, for when a miss is a reason to try something else
    /// rather than to end the test.
    @discardableResult
    static func tapExactIfPresent(_ app: XCUIApplication, _ label: String) -> Bool {
        let predicate = NSPredicate(format: "label == %@", label)
        for query in [app.buttons, app.links, app.otherElements, app.staticTexts] {
            let match = query.matching(predicate).firstMatch
            if match.exists && match.isHittable { match.tap(); usleep(1_500_000); return true }
        }
        return false
    }

    @discardableResult
    static func tapIfPresent(_ app: XCUIApplication, containing text: String) -> Bool {
        guard let element = find(app, containing: text), element.exists else { return false }
        if element.isHittable { element.tap() }
        else { element.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.5)).tap() }
        usleep(1_500_000)
        return true
    }

    /// Put the keyboard away.
    ///
    /// The command palette opens with its field focused, so the software
    /// keyboard covers the bottom half of the results — including, for a query
    /// like "billing", the Settings row that is the actual target. The row is
    /// present in the accessibility tree the whole time, so a tap "succeeds"
    /// and lands on a keycap instead. Dismissing first is what makes the list
    /// reachable. The Done button belongs to the WebView's input accessory bar.
    /// Put the keyboard away, and say whether it actually went.
    ///
    /// The return value matters. The palette opens focused, so its lower
    /// results are in the accessibility tree, report themselves hittable, and
    /// are physically behind a keycap — tapping one presses a letter. The old
    /// version tapped "Done" once, returned nothing, and callers carried on
    /// regardless: on 2026-08-21 that put a tap into the keyboard, left the
    /// palette open over the whole app, and the NEXT surface then spent 30s
    /// failing to find a top bar the palette was covering. The visible symptom
    /// was 40s of nothing in a completely unrelated place.
    ///
    /// Verifies rather than assumes, because "Done" is not always a button
    /// labelled Done — the form accessory above a web input renders it as a
    /// checkmark glyph, and whether it is hittable depends on where the
    /// keyboard is in its animation.
    @discardableResult
    static func dismissKeyboard(_ app: XCUIApplication) -> Bool {
        for _ in 0..<4 {
            guard app.keyboards.element.exists else { return true }
            let candidates: [XCUIElement] = [
                app.buttons["Done"],
                app.toolbars.buttons["Done"],
                app.keyboards.buttons["Done"],
                // NOT app.buttons["Return"]. Return does not dismiss the
                // palette's keyboard, it SUBMITS — activating whichever result
                // is selected and closing the palette. Listing it as a fallback
                // made every later `tapInSectionIfPresent` report "could not
                // reach X from the palette", because by then the palette was
                // gone and the app was on some other page entirely.
            ]
            for candidate in candidates where candidate.exists && candidate.isHittable {
                candidate.tap()
                break
            }
            usleep(700_000)
        }
        return !app.keyboards.element.exists
    }

    /// Close the command palette if something left it open.
    ///
    /// A guard against cascade: the palette is a full-screen overlay, so one
    /// surface failing to navigate leaves every later surface unable to see the
    /// app at all. Cheap, and it turns a run of mysterious failures back into
    /// the single real one.
    static func closePaletteIfOpen(_ app: XCUIApplication) {
        guard app.keyboards.element.exists || find(app, containing: "Search or jump") == nil else { return }
        dismissKeyboard(app)
        guard find(app, containing: "Search or jump") == nil else { return }
        // Still covered, so the palette really is open. Tap its backdrop: the
        // panel occupies the lower half of a phone screen, so a tap near the
        // top is outside it. A coordinate on the APP rather than on a found
        // element, because the thing to hit is deliberately the absence of one.
        app.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.06)).tap()
        usleep(700_000)
    }

    /// Tap `item` INSIDE the group labelled `section`.
    ///
    /// The command palette needs this. Typing "billing" leaves two things
    /// labelled exactly "Billing" on screen: the *Billing* section header,
    /// which groups Invoices and Payments, and the *Billing* row under
    /// *Settings*. A substring search finds the section first and taps a header
    /// that goes nowhere — which is precisely how the first version of this
    /// harness failed. Scoping to the section makes the target unambiguous.
    @discardableResult
    static func tapInSection(
        _ app: XCUIApplication,
        section: String,
        item: String,
        timeout: TimeInterval = elementTimeout,
        file: StaticString = #filePath,
        line: UInt = #line
    ) -> Bool {
        let sectionPredicate = NSPredicate(format: "label == %@", section)
        let itemPredicate = NSPredicate(format: "label == %@", item)
        let deadline = Date().addingTimeInterval(timeout)
        while Date() < deadline {
            let group = app.otherElements.matching(sectionPredicate).firstMatch
            if group.exists {
                let row = group.otherElements.matching(itemPredicate).firstMatch
                if row.exists {
                    if row.isHittable { row.tap() }
                    else { row.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.5)).tap() }
                    return true
                }
            }
            usleep(400_000)
        }
        XCTFail("never found “\(item)” inside the “\(section)” group within \(timeout)s", file: file, line: line)
        return false
    }

    /// Type into the focused field, PROVING focus first.
    ///
    /// ── WHY THIS IS NOT JUST `typeText` ───────────────────────────────────
    ///
    /// It used to wait for a text field to EXIST and then type at the
    /// application. Existing is not focused, and when it was not, XCUITest
    /// raised "Failed to synthesize event: Neither element nor any descendant
    /// has keyboard focus" — a message that names no element and no screen.
    /// That single line accounts for most of the noise in this suite's history:
    /// it failed the billing gate, the client billing pair, the invoice
    /// legibility test and every ScrollSweep surface at one time or another,
    /// always looking like a different bug.
    ///
    /// The keyboard is the only honest proof that something is focused, so this
    /// waits for it, and taps the field itself if it never arrives. Returns
    /// whether it managed to type, so callers can skip rather than assert
    /// against a screen they never reached.
    @discardableResult
    static func type(_ app: XCUIApplication, _ value: String) -> Bool {
        let field = app.textFields.firstMatch
        _ = field.waitForExistence(timeout: elementTimeout)

        for attempt in 0..<3 {
            if app.keyboards.element.waitForExistence(timeout: 5) {
                app.typeText(value)
                return true
            }
            // No keyboard: nothing is focused. Tap the field and try again.
            if field.exists {
                if field.isHittable { field.tap() }
                else { field.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.5)).tap() }
            }
            usleep(600_000)
            if attempt == 2 {
                XCTFail(
                    "nothing took keyboard focus after 3 attempts, so \"\(value)\" was never "
                        + "typed. The field exists=\(field.exists); this is the harness, not "
                        + "necessarily the product."
                )
            }
        }
        return false
    }

    /// Open the command palette and prove it took focus before typing.
    ///
    /// Tapping the trigger and typing immediately is a coin flip on a cold
    /// launch: the trigger is present and hittable a moment before the WebView
    /// will act on a tap, so the tap lands, nothing opens, and `typeText`
    /// fails with "Neither element nor any descendant has keyboard focus" —
    /// which reads like a broken app rather than a mistimed tap.
    ///
    /// The keyboard is the honest signal that the field is really focused, so
    /// this waits for it and taps again if it never came.
    @discardableResult
    static func openPalette(_ app: XCUIApplication, attempts: Int = 3) -> Bool {
        for _ in 0..<attempts {
            closePaletteIfOpen(app)
            // A SILENT probe. `tap` fails the test when it cannot find its
            // element, which inside a retry loop means two recorded failures
            // for a palette the third attempt opened perfectly well — and 30s
            // burned per attempt. Retries must not report.
            guard let trigger = waitForExists(app, containing: "Search or jump", timeout: 20)
                ? find(app, containing: "Search or jump") : nil
            else { continue }
            if trigger.isHittable { trigger.tap() }
            else { trigger.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.5)).tap() }
            let deadline = Date().addingTimeInterval(5)
            while Date() < deadline {
                if app.keyboards.element.exists { return true }
                usleep(300_000)
            }
        }
        return app.keyboards.element.exists
    }

    /// Put the page back at the top.
    ///
    /// Navigating by palette can leave the destination scrolled — the route
    /// renders, and the element a test waits for is above the viewport. That
    /// looked exactly like a broken page: `testBillingGateHidesEveryPurchase-
    /// Control` failed with "never found Current plan within 60s" on a screen
    /// that was showing the billing route perfectly, two cards further down.
    static func scrollToTop(_ app: XCUIApplication) {
        let target = app.scrollViews.firstMatch.exists ? app.scrollViews.firstMatch
                                                       : app.windows.firstMatch
        for _ in 0..<6 {
            target.swipeDown()
            usleep(250_000)
        }
    }

    /// Scroll the main scroll view down one screenful. Returns false when the
    /// view did not move, which is how callers know they have hit the bottom.
    @discardableResult
    static func pageDown(_ app: XCUIApplication) -> Bool {
        let before = app.debugDescription.count
        let target = app.scrollViews.firstMatch.exists ? app.scrollViews.firstMatch : app.windows.firstMatch
        target.swipeUp()
        usleep(700_000)
        return app.debugDescription.count != before
    }

    // MARK: - Evidence

    /// Attach a full-screen screenshot to the test result, kept even when the
    /// test passes — the point of this harness is the evidence, not just the
    /// pass. Extract with `xcrun xcresulttool`; see ios/UITests/README.md.
    static func screenshot(_ name: String, _ test: XCTestCase) {
        let shot = XCUIScreen.main.screenshot()
        let attachment = XCTAttachment(screenshot: shot)
        attachment.name = name
        attachment.lifetime = .keepAlways
        test.add(attachment)
    }
}
