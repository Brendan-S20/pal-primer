// The one lint rule that is a CRASH detector, gated hard on its own.
//
// The main config's CI step is `continue-on-error: true` on top of ~24,000
// pre-existing stylistic errors, which makes it decorative: on 2026-09-26 it
// SAW `react-hooks/rules-of-hooks` fire on clients.$clientId.tsx — a
// useOrgToday() placed after the component's early returns — and the job
// stayed green. That hook rendered the router's error boundary on every
// visit to /clients/:id; the viewport sweep caught it on main, one merge
// too late.
//
// rules-of-hooks is not a style opinion. A conditional hook is a component
// that unmounts itself at runtime, and it is the exact fault a type checker
// cannot see (the call compiles) and a unit test rarely reaches (it needs
// the loading render AND the loaded render). Zero violations as of today,
// so `npm run check:hooks` is a ratchet: a failure means a NEW conditional
// hook, never old debt.
//
// Deliberately not `exhaustive-deps` — that one is a judgement this repo
// overrides on purpose in several places, and a gate nobody can keep green
// gets continue-on-error next, which is how this file's reason-to-exist
// happened the first time.
import reactHooks from "eslint-plugin-react-hooks";
import tseslint from "typescript-eslint";

export default tseslint.config(
  {
    ignores: [
      "dist",
      ".output",
      ".vinxi",
      "dist-native",
      "ios",
      "android",
      "node_modules",
      // Generated by the router; not authored, not worth parsing.
      "src/routeTree.gen.ts",
    ],
  },
  // The main config enables exhaustive-deps, so src carries inline disables
  // for it. This config deliberately does not, and without this switch every
  // one of those disables reports as "unused" here — 27 warnings of pure
  // noise around the dozen errors that matter.
  { linterOptions: { reportUnusedDisableDirectives: "off" } },
  {
    files: ["src/**/*.{ts,tsx}"],
    languageOptions: {
      parser: tseslint.parser,
      parserOptions: { ecmaFeatures: { jsx: true } },
    },
    plugins: { "react-hooks": reactHooks },
    rules: {
      "react-hooks/rules-of-hooks": "error",
    },
  },
);
